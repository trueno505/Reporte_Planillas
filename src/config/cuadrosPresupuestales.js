// Compara nombres de área ignorando tildes, mayúsculas y espacios extra,
// para tolerar pequeñas diferencias entre config y datos guardados.
function normalizar(s) {
  return String(s ?? '')
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/\s+/g, ' ')
    .trim()
    .toUpperCase()
}

/**
 * Devuelve el cuadro presupuestal de un área (o el cuadro único de la planilla
 * si `area` es null y la planilla no se divide por áreas). null si no hay.
 */
export function getCuadroArea(slug, area) {
  const p = CUADROS_PRESUPUESTALES[slug]
  if (!p) return null
  if (area == null) {
    return p.cuadro ? { oficina: p.oficina, ...p.cuadro } : null
  }
  if (!p.areas) return null
  const clave = Object.keys(p.areas).find((k) => normalizar(k) === normalizar(area))
  if (!clave) return null
  const c = p.areas[clave]
  return { ...c, oficina: c.oficina ?? p.oficina }
}
